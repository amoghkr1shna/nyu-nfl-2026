"""Export the results the interactive page needs to docs/data.js.

The page (docs/index.html) is plain HTML + JS with no build step. It reads
`window.FINDINGS` from data.js, which works both from the file system and on
GitHub Pages.

    python -m src.site
"""

from __future__ import annotations

import json

import pandas as pd

from src.paths import OUTPUTS, ROOT

DOCS = ROOT / "docs"
DATA_JS = DOCS / "data.js"


def build() -> dict:
    effect = pd.read_csv(OUTPUTS / "coverage_effect.csv")
    board = pd.read_csv(OUTPUTS / "leaderboard.csv")
    model = pd.read_csv(OUTPUTS / "regression_summary.csv")
    routes = pd.read_csv(OUTPUTS / "route_metrics.csv",
                         usecols=["gameId", "playId", "coverage"])

    terms = model.loc[model["term"].isin(["is_man", "man_x_angle", "speed_kept"])]
    return {
        "totals": {
            "routes": int(len(routes)),
            "man": int(routes["coverage"].eq("Man").sum()),
            "zone": int(routes["coverage"].eq("Zone").sum()),
            "plays": int(routes.groupby(["gameId", "playId"]).ngroups),
            "games": int(routes["gameId"].nunique()),
        },
        "effect": effect.round(3).to_dict(orient="records"),
        "model": {
            pos: {r.term: {"coef": round(r.coef_yd, 3), "t": round(r.t, 1)}
                  for r in grp.itertuples()}
            for pos, grp in terms.groupby("position")
        },
        "players": board[[
            "position", "shiftiness_rank", "displayName", "routes", "routes_man",
            "routes_zone", "shiftiness", "avg_cut_angle", "real_cut_rate",
            "gain_man", "gain_zone",
        ]].round(3).to_dict(orient="records"),
    }


def main() -> None:
    DOCS.mkdir(exist_ok=True)
    payload = json.dumps(build(), separators=(",", ":"))
    DATA_JS.write_text(f"// Generated by src/site.py from outputs/. Do not edit.\n"
                       f"window.FINDINGS = {payload};\n")
    print(f"saved {DATA_JS.relative_to(ROOT)} ({DATA_JS.stat().st_size / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
